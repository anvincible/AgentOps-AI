from backend.app.sql.sql_agent import SQLAgent
from backend.app.database_config import load_database_config


def run_test(
    agent: SQLAgent,
    test_number: int,
    question: str,
    expected_columns: list[str],
):
    print("\n" + "=" * 70)
    print(f"TEST {test_number}")
    print("=" * 70)

    print("\nQuestion:")
    print(question)

    try:
        response = agent.answer(question)

        print("\nGenerated SQL:")
        print("-" * 70)
        print(response["sql"])

        print("\nValidation:")
        print("-" * 70)
        print(response["validation"])

        print("\nDatabase Result:")
        print("-" * 70)

        result = response["result"]

        print("Columns:")
        print(result["columns"])

        print("\nRows:")

        for row in result["rows"]:
            print(row)

        print("\nRow count:")
        print(result["row_count"])

        # -----------------------------------------------------
        # Assertions
        # -----------------------------------------------------

        assert response["validation"]["valid"] is True

        for column in expected_columns:
            assert column in result["columns"]

        assert result["row_count"] > 0

        print("\nPASS")

    except Exception as error:
        print("\nFAIL")
        print(f"Error: {error}")
        raise


def main():
    print("=" * 70)
    print("TESTING SQL AGENT - MULTIPLE QUESTIONS")
    print("=" * 70)

    # ---------------------------------------------------------
    # Database configuration
    # ---------------------------------------------------------


    # ---------------------------------------------------------
    # Create SQL Agent
    # ---------------------------------------------------------

    db_config = load_database_config(require_explicit=True)
    agent = SQLAgent(
        **db_config,
        max_rows=100,
    )

    # =========================================================
    # TEST 1 — Revenue
    # =========================================================

    run_test(
        agent=agent,
        test_number=1,
        question=(
            "What was the revenue generated by campaign CMP-021?"
        ),
        expected_columns=[
            "campaign_id",
            "campaign_name",
            "revenue_generated",
        ],
    )

    # =========================================================
    # TEST 2 — Spend
    # =========================================================

    run_test(
        agent=agent,
        test_number=2,
        question=(
            "What was the spend of campaign CMP-021?"
        ),
        expected_columns=[
            "campaign_id",
            "campaign_name",
            "actual_spend",
        ],
    )

    # =========================================================
    # TEST 3 — Conversions
    # =========================================================

    run_test(
        agent=agent,
        test_number=3,
        question=(
            "How many conversions did campaign CMP-021 generate?"
        ),
        expected_columns=[
            "campaign_id",
            "campaign_name",
            "conversions",
        ],
    )

    # =========================================================
    # TEST 4 — Campaign Performance
    # =========================================================

    run_test(
        agent=agent,
        test_number=4,
        question=(
            "What was the performance of campaign CMP-021?"
        ),
        expected_columns=[
            "campaign_id",
            "campaign_name",
            "actual_spend",
            "revenue_generated",
            "conversions",
            "clicks",
        ],
    )

    # =========================================================
    # TEST 5 — Unsupported Question
    # =========================================================

    print("\n" + "=" * 70)
    print("TEST 5")
    print("=" * 70)

    question = (
        "What is the average order value of customers?"
    )

    print("\nQuestion:")
    print(question)

    try:
        agent.answer(question)

        raise AssertionError(
            "The unsupported question should have raised "
            "a ValueError."
        )

    except ValueError as error:
        print("\nExpected error:")
        print(error)

        print("\nPASS")

    # =========================================================
    # Final Result
    # =========================================================

    print("\n" + "=" * 70)
    print("ALL SQL AGENT TESTS COMPLETED SUCCESSFULLY")
    print("=" * 70)


if __name__ == "__main__":
    main()