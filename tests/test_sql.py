import pytest

from backend.app.sql.sql_generator import SQLGenerator
from backend.app.sql.sql_reasoner import SQLReasoner
from backend.app.sql.sql_validator import SQLValidator


@pytest.mark.unit
@pytest.mark.parametrize(
    ("question", "intent", "column"),
    [
        ("What was the revenue generated by campaign CMP-021?", "REVENUE", "revenue_generated"),
        ("What was the spend of campaign CMP-021?", "SPEND", "actual_spend"),
        ("How many conversions did campaign CMP-021 generate?", "CONVERSIONS", "conversions"),
    ],
)
def test_campaign_question_classification(
    schema_loader, question, intent, column
):
    plan = SQLReasoner(schema_loader).reason(question)

    assert plan["intent"] == intent
    assert plan["entity_id"] == "CMP-021"
    assert column in plan["columns"]


@pytest.mark.unit
def test_campaign_cmp021_query_planning(schema_loader):
    plan = SQLReasoner(schema_loader).reason(
        "What was the performance of campaign CMP-021?"
    )

    assert plan["intent"] == "CAMPAIGN_PERFORMANCE"
    assert plan["table"] == "marketing_campaigns"
    assert plan["filters"] == [
        {"column": "campaign_id", "operator": "=", "value": "CMP-021"}
    ]


@pytest.mark.unit
def test_campaign_comparison_and_roi_generation(schema_loader):
    reasoner = SQLReasoner(schema_loader)
    generator = SQLGenerator(schema_loader)

    comparison = generator.generate_sql(
        reasoner.reason("Compare campaigns CMP-021 and CMP-022.")
    )
    roi = generator.generate_sql(
        reasoner.reason("What is the ROI of campaign CMP-021?")
    )

    assert "campaign_id IN ('CMP-021', 'CMP-022')" in comparison
    assert "roi_percent" not in comparison
    assert "roi_percent" in roi
    assert "NULLIF(actual_spend, 0)" in roi


