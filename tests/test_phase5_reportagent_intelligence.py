def test_metric_value_status_handling():
    """Verify distinction between zero, missing, unavailable, and not applicable."""
    val_zero = ValidatedMetricValue("total_orders", 0, MetricValueStatus.ZERO)
    assert val_zero.format_value() == "0"
    assert val_zero.is_available is True

    val_unavail = ValidatedMetricValue("campaign_roas", None, MetricValueStatus.UNAVAILABLE)
