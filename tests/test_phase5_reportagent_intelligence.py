def test_contradiction_detection_flags_false_concentration(data_layer):
    """Verify contradiction detection catches false category concentration claims."""
    data = data_layer.retrieve_and_validate(ReportCategory.EXECUTIVE_PERFORMANCE, ReportPeriod.ALL_TIME)
    
    # In reality: Electronics is ~46.9% and Home & Kitchen is ~10.6% (sum 57.5%)
    # Claiming "Electronics and Home & Kitchen account for over 65% of revenue" is a contradiction!
    false_statement = (
        "Category Concentration Risk: [Measured Fact] Over 65% of gross revenue is generated by "
        "Electronics and Home & Kitchen across departmental sales."
    )
    is_valid, issues = InsightValidator.validate_contradictions(false_statement, data)
    assert is_valid is False
    assert any("contradiction in category concentration" in iss.lower() for iss in issues)


