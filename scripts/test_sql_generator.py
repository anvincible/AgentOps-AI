from backend.app.sql.schema_inspector import DatabaseSchemaLoader
from backend.app.sql.sql_generator import SQLGenerator


def main():
    print("=" * 70)
    print("TESTING SQL GENERATOR")
    print("=" * 70)

    # ---------------------------------------------------------
    # Database configuration
    # ---------------------------------------------------------

    schema_loader = DatabaseSchemaLoader(
        host="localhost",
        port=5432,
        database="novamart",
        user="postgres",
        password="YOUR_POSTGRES_PASSWORD",
    )

    # ---------------------------------------------------------
    # Create SQL Generator
    # ---------------------------------------------------------

    generator = SQLGenerator(schema_loader)

    # ---------------------------------------------------------
    # Test 1: Revenue
    # ---------------------------------------------------------

    question = (
        "What was the revenue generated by campaign CMP-021?"
    )

    print("\nTest 1: Revenue")
    print("-" * 70)

    print("Natural-language question:")
    print(f"  {question}")

    sql = generator.generate_sql(question)

    print("\nGenerated SQL:")
    print(sql)

    assert "revenue_generated" in sql

    assert "marketing_campaigns" in sql

    assert "CMP-021" in sql

    print("\nPASS")

    # ---------------------------------------------------------
    # Test 2: Actual spend
    # ---------------------------------------------------------

    question = (
        "What was the spend of campaign CMP-021?"
    )

    print("\nTest 2: Campaign spend")
    print("-" * 70)

    print("Natural-language question:")
    print(f"  {question}")

    sql = generator.generate_sql(question)

    print("\nGenerated SQL:")
    print(sql)

    assert "actual_spend" in sql

    assert "marketing_campaigns" in sql

    assert "CMP-021" in sql

    print("\nPASS")

    # ---------------------------------------------------------
    # Test 3: Conversions
    # ---------------------------------------------------------

    question = (
        "How many conversions did campaign CMP-021 generate?"
    )

    print("\nTest 3: Campaign conversions")
    print("-" * 70)

    print("Natural-language question:")
    print(f"  {question}")

    sql = generator.generate_sql(question)

    print("\nGenerated SQL:")
    print(sql)

    assert "conversions" in sql

    assert "marketing_campaigns" in sql

    assert "CMP-021" in sql

    print("\nPASS")

    # ---------------------------------------------------------
    # Test 4: Overall campaign performance
    # ---------------------------------------------------------

    question = (
        "What was the performance of campaign CMP-021?"
    )

    print("\nTest 4: Campaign performance")
    print("-" * 70)

    print("Natural-language question:")
    print(f"  {question}")

    sql = generator.generate_sql(question)

    print("\nGenerated SQL:")
    print(sql)

    assert "actual_spend" in sql

    assert "revenue_generated" in sql

    assert "conversions" in sql

    assert "clicks" in sql

    assert "marketing_campaigns" in sql

    assert "CMP-021" in sql

    print("\nPASS")

    # ---------------------------------------------------------
    # Test 5: Empty question
    # ---------------------------------------------------------

    print("\nTest 5: Empty question")
    print("-" * 70)

    try:
        generator.generate_sql("")

        raise AssertionError(
            "Empty question should have raised ValueError."
        )

    except ValueError as error:
        print(f"Expected error: {error}")

    print("PASS")

    # ---------------------------------------------------------
    # Test 6: Unsupported question
    # ---------------------------------------------------------

    print("\nTest 6: Unsupported question")
    print("-" * 70)

    unsupported_question = (
        "What is the average order value of customers?"
    )

    try:
        generator.generate_sql(unsupported_question)

        raise AssertionError(
            "Unsupported question should have raised ValueError."
        )

    except ValueError as error:
        print(f"Expected error: {error}")

    print("PASS")

    # ---------------------------------------------------------
    # Final result
    # ---------------------------------------------------------

    print("\n" + "=" * 70)
    print("SQL GENERATOR TEST COMPLETED SUCCESSFULLY")
    print("=" * 70)


if __name__ == "__main__":
    main()