def test_category_returns_distinguishes_contribution_vs_rate(data_layer):
    """Verify category return rate and return contribution are properly separated."""
    data = data_layer.retrieve_and_validate(ReportCategory.OPERATIONS_FULFILLMENT, ReportPeriod.ALL_TIME)
    assert hasattr(data, "category_returns")
    assert len(data.category_returns) == 6

    # Verify return contributions sum to ~100%
    contributions = [cr["return_contribution_pct"] for cr in data.category_returns]
    assert abs(sum(contributions) - 100.0) <= 1.5

    # Verify category return rates are tightly clustered (3.1% to 3.6%)
    for cr in data.category_returns:
        rate = cr["category_return_rate_pct"]
        assert 2.0 <= rate <= 5.0, f"Unexpected return rate for {cr['category']}: {rate}"


def test_product_pricing_and_discount_reconciliation(data_layer):
    """Verify that line-item revenue accounts for promotional discounts."""
    data = data_layer.retrieve_and_validate(ReportCategory.SALES_PERFORMANCE, ReportPeriod.ALL_TIME)
    assert len(data.top_products) > 0

    hero_sku = data.top_products[0]
    assert "list_price" in hero_sku
    assert "units_sold" in hero_sku
    assert "total_discounts" in hero_sku
    assert "gross_list_value" in hero_sku
    assert "total_revenue" in hero_sku

