from backend.app.sql.sql_agent import SQLAgent
from backend.app.database_config import load_database_config


def main():
    print("=" * 70)
    print("TESTING SQL AGENT")
    print("=" * 70)

    # ---------------------------------------------------------
    # Database configuration
    # ---------------------------------------------------------


    # ---------------------------------------------------------
    # Create SQL Agent
    # ---------------------------------------------------------

    db_config = load_database_config(require_explicit=True)
    agent = SQLAgent(
        **db_config,
        max_rows=100,
    )

    # ---------------------------------------------------------
    # Test question
    # ---------------------------------------------------------

    question = (
        "What was the revenue generated by campaign CMP-021?"
    )

    print("\nNatural-language question:")
    print(f"  {question}")

    # ---------------------------------------------------------
    # Run complete SQL Agent
    # ---------------------------------------------------------

    print("\nRunning SQL Agent...")
    print("-" * 70)

    response = agent.answer(question)

    # ---------------------------------------------------------
    # Display generated SQL
    # ---------------------------------------------------------

    print("\nGenerated SQL:")
    print("-" * 70)
    print(response["sql"])

    # ---------------------------------------------------------
    # Display validation result
    # ---------------------------------------------------------

    print("\nValidation result:")
    print("-" * 70)
    print(response["validation"])

    # ---------------------------------------------------------
    # Display database result
    # ---------------------------------------------------------

    print("\nDatabase result:")
    print("-" * 70)

    result = response["result"]

    print("Columns:")
    print(result["columns"])

    print("\nRows:")

    for row in result["rows"]:
        print(row)

    print("\nRow count:")
    print(result["row_count"])

    # ---------------------------------------------------------
    # Assertions
    # ---------------------------------------------------------

    assert response["question"] == question

    assert response["validation"]["valid"] is True

    assert response["result"]["row_count"] == 1

    assert "campaign_id" in response["result"]["columns"]

    assert "campaign_name" in response["result"]["columns"]

    assert "revenue_generated" in response["result"]["columns"]

    row = response["result"]["rows"][0]

    assert row[0] == "CMP-021"

    assert row[1] == "NovaMart Growth Campaign 21"

    assert float(row[2]) == 5270000.00

    # ---------------------------------------------------------
    # Final result
    # ---------------------------------------------------------

    print("\n" + "=" * 70)
    print("SQL AGENT TEST COMPLETED SUCCESSFULLY")
    print("=" * 70)


if __name__ == "__main__":
    main()