from backend.app.sql.sql_reasoner import SQLReasoner
from backend.app.sql.schema_inspector import DatabaseSchemaLoader
from backend.app.sql.sql_generator import SQLGenerator
from backend.app.sql.sql_validator import SQLValidator
from backend.app.sql.sql_executor import SQLExecutor


def main():
    print("=" * 70)
    print("TESTING SQL EXECUTOR")
    print("=" * 70)

    # ---------------------------------------------------------
    # Database configuration
    # ---------------------------------------------------------

    password = "agentops"

    # ---------------------------------------------------------
    # Create database components
    # ---------------------------------------------------------

    schema_loader = DatabaseSchemaLoader(
        host="localhost",
        port=5432,
        database="novamart",
        user="postgres",
        password=password,
    )

    schema = schema_loader.load_schema()

    validator = SQLValidator(schema)

    generator = SQLGenerator(schema_loader)

    executor = SQLExecutor(
        host="localhost",
        port=5432,
        database="novamart",
        user="postgres",
        password=password,
        max_rows=100,
    )

    # ---------------------------------------------------------
    # Generate SQL
    # ---------------------------------------------------------

    question = "What was the revenue generated by campaign CMP-021?"

    print("\nNatural-language question:")
    print(f"  {question}")

    reasoner = SQLReasoner(schema_loader)
    query_plan = reasoner.reason(question)
    sql = generator.generate_sql(query_plan)

    print("\nGenerated SQL:")
    print("-" * 70)
    print(sql)

    # ---------------------------------------------------------
    # Validate SQL
    # ---------------------------------------------------------

    print("\nValidating SQL...")

    validation_result = validator.validate(sql)

    print(validation_result)

    if not validation_result["valid"]:
        raise ValueError(
            "Generated SQL failed validation: "
            f"{validation_result['errors']}"
        )

    print("SQL validation: PASS")

    # ---------------------------------------------------------
    # Execute SQL
    # ---------------------------------------------------------

    print("\nExecuting SQL...")
    print("-" * 70)

    result = executor.execute(sql)

    # ---------------------------------------------------------
    # Display result
    # ---------------------------------------------------------

    print("\nColumns:")
    print(result["columns"])

    print("\nRows:")

    for row in result["rows"]:
        print(row)

    print("\nRow count:")
    print(result["row_count"])

    # ---------------------------------------------------------
    # Basic assertions
    # ---------------------------------------------------------

    assert result["row_count"] > 0

    assert "campaign_id" in result["columns"]

    assert "campaign_name" in result["columns"]

    assert "revenue_generated" in result["columns"]

    print("\n" + "=" * 70)
    print("SQL EXECUTOR TEST COMPLETED SUCCESSFULLY")
    print("=" * 70)


if __name__ == "__main__":
    main()