import re
from typing import Any


class SQLValidator:
    """
    Validates SQL generated by the SQL Agent.

    Phase 3.3 responsibilities:
    - Allow only SELECT queries
    - Block write/DDL operations
    - Prevent multiple SQL statements
    - Check that referenced tables exist
    - Return clear validation errors
    """

    BLOCKED_KEYWORDS = {
        "INSERT",
        "UPDATE",
        "DELETE",
        "DROP",
        "ALTER",
        "TRUNCATE",
        "CREATE",
        "GRANT",
        "REVOKE",
        "MERGE",
        "CALL",
        "EXECUTE",
        "COPY",
        "VACUUM",
        "ANALYZE",
        "SET",
        "DO",
        "BEGIN",
        "COMMIT",
        "ROLLBACK",
    }

    def __init__(self, schema: dict[str, Any]):
        self.schema = schema

        self.valid_tables = set(
            schema.get("tables", {}).keys()
        )

    def validate(self, sql: str) -> dict[str, Any]:
        """
        Validate a SQL query.

        Returns:
            {
                "valid": bool,
                "errors": list[str],
                "tables": list[str]
            }
        """

        errors: list[str] = []

        if not sql or not sql.strip():
            return {
                "valid": False,
                "errors": ["SQL query cannot be empty."],
                "tables": [],
            }

        cleaned_sql = self._remove_comments(sql).strip()

        # ---------------------------------------------------------
        # 1. Check multiple statements
        # ---------------------------------------------------------

        semicolon_positions = [
            match.start()
            for match in re.finditer(";", cleaned_sql)
        ]

        if len(semicolon_positions) > 1:
            errors.append(
                "Multiple SQL statements are not allowed."
            )

        elif len(semicolon_positions) == 1:
            semicolon_position = semicolon_positions[0]

            if cleaned_sql[semicolon_position + 1 :].strip():
                errors.append(
                    "Multiple SQL statements are not allowed."
                )

        # ---------------------------------------------------------
        # 2. Query must start with SELECT
        # ---------------------------------------------------------

        if not re.match(
            r"^\s*SELECT\b",
            cleaned_sql,
            re.IGNORECASE,
        ):
            errors.append(
                "Only SELECT queries are allowed."
            )

        if not re.search(r"\bFROM\b", cleaned_sql, re.IGNORECASE):
            errors.append("Malformed SQL query: FROM clause is required.")

        select_match = re.match(
            r"^\s*SELECT\b(.*?)\bFROM\b",
            cleaned_sql,
            re.IGNORECASE | re.DOTALL,
        )

        if select_match and not select_match.group(1).strip():
            errors.append("Malformed SQL query: SELECT list is empty.")

        if cleaned_sql.count("(") != cleaned_sql.count(")"):
            errors.append("Malformed SQL query: unbalanced parentheses.")

        # ---------------------------------------------------------
        # 3. Check blocked SQL operations
        # ---------------------------------------------------------

        for keyword in self.BLOCKED_KEYWORDS:
            pattern = rf"\b{keyword}\b"

            if re.search(
                pattern,
                cleaned_sql,
                re.IGNORECASE,
            ):
                errors.append(
                    f"Blocked SQL operation detected: {keyword}"
                )

        # ---------------------------------------------------------
        # 4. Extract referenced tables
        # ---------------------------------------------------------

        referenced_tables = self._extract_tables(cleaned_sql)

        if not referenced_tables:
            errors.append(
                "No database table could be identified in the SQL query."
            )

        # ---------------------------------------------------------
        # 5. Validate table names
        # ---------------------------------------------------------

        for table_name in referenced_tables:

            normalized_table = table_name

            if normalized_table.startswith("public."):
                normalized_table = normalized_table[
                    len("public.") :
                ]

            if normalized_table not in self.valid_tables:
                errors.append(
                    f"Table does not exist in the NovaMart database: "
                    f"{normalized_table}"
                )

        if select_match and referenced_tables:
            # Validate selected columns against ALL referenced tables, not
            # only the first one. A query may legitimately pull a column from
            # any table in the FROM/JOIN clause or from a subquery alias.
            valid_columns: set[str] = set()
            for table_ref in referenced_tables:
                normalized_table = table_ref.split(".")[-1]
                for column in self.schema.get("tables", {}).get(
                    normalized_table, {}
                ).get("columns", []):
                    valid_columns.add(column["column_name"])

            # Derived/alias columns (e.g. COUNT(*) AS return_count) are
            # declared inside the query itself. Accepting the names the query
            # introduces does not weaken the table/column validation performed
            # above, and the query remains restricted to SELECT against
            # tables that exist in the schema.
            derived_aliases = self._extract_alias_names(
                cleaned_sql, valid_columns
            )

            # Check the projection of the outer query and of every subquery,
            # so plain column references inside subqueries are validated
            # against the real schema too.
            reported: set[str] = set()
            for projection in re.finditer(
                r"\bSELECT\b(.*?)\bFROM\b",
                cleaned_sql,
                re.IGNORECASE | re.DOTALL,
            ):
                for selected_column in self._extract_simple_columns(
                    projection.group(1)
                ):
                    if selected_column == "*":
                        continue
                    if selected_column in valid_columns:
                        continue
                    if selected_column in derived_aliases:
                        continue
                    if selected_column in reported:
                        continue
                    reported.add(selected_column)
                    errors.append(
                        "Column does not exist in any referenced table: "
                        f"{selected_column}"
                    )

        return {
            "valid": len(errors) == 0,
            "errors": errors,
            "tables": referenced_tables,
        }

    # -------------------------------------------------------------
    # Helper methods
    # -------------------------------------------------------------

    @staticmethod
    def _remove_comments(sql: str) -> str:
        """
        Remove SQL comments before validation.
        """

        # Remove -- comments
        sql = re.sub(
            r"--.*?$",
            "",
            sql,
            flags=re.MULTILINE,
        )

        # Remove /* ... */ comments
        sql = re.sub(
            r"/\*.*?\*/",
            "",
            sql,
            flags=re.DOTALL,
        )

        return sql

    @staticmethod
    def _extract_tables(sql: str) -> list[str]:
        """
        Extract table names appearing after FROM and JOIN.
        """

        pattern = (
            r"\b(?:FROM|JOIN)\s+"
            r"([A-Za-z_][A-Za-z0-9_]*"
            r"(?:\.[A-Za-z_][A-Za-z0-9_]*)?)"
        )

        matches = re.findall(
            pattern,
            sql,
            flags=re.IGNORECASE,
        )

        return list(dict.fromkeys(matches))

    @staticmethod
    def _extract_alias_names(sql: str, valid_columns: set[str]) -> set[str]:
        """
        Return column/table aliases declared in the query.

        These names are introduced by the query itself (for example
        ``COUNT(*) AS return_count`` or ``(...) AS r``) and are valid
        references in the SELECT projection even though they are not real
        schema columns. Accepting them does not weaken table or column
        existence checks: every underlying table must still exist in the
        schema, and blocked write/DDL keywords remain rejected.
        """

        aliases: set[str] = set()

        # Column aliases:  <expr> AS <name>
        # A bare identifier renamed with AS (e.g. ``missing_col AS x``) is
        # not a derived value: it is only trusted when the source is a real
        # column. Expressions (functions, arithmetic, CASE ... END) are
        # derived values and their alias is trusted.
        for match in re.finditer(
            r"([A-Za-z_][A-Za-z0-9_.]*|\S)\s+AS\s+([A-Za-z_][A-Za-z0-9_]*)",
            sql,
            flags=re.IGNORECASE,
        ):
            source = match.group(1).split(".")[-1]
            is_bare = re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", source)
            if (
                is_bare
                and source.upper() != "END"
                and source not in valid_columns
            ):
                continue
            aliases.add(match.group(2))

        # Subquery table aliases:  FROM ( ... ) AS <name>
        for match in re.finditer(
            r"\)\s+AS\s+([A-Za-z_][A-Za-z0-9_]*)",
            sql,
            flags=re.IGNORECASE,
        ):
            aliases.add(match.group(1))

        return aliases

    @staticmethod
    def _extract_simple_columns(select_list: str) -> list[str]:
        """Return plain column references from a SELECT projection."""

        columns: list[str] = []
        for expression in select_list.split(","):
            expression = expression.strip()
            match = re.fullmatch(
                r"(?:[A-Za-z_][A-Za-z0-9_]*\.)?"
                r"([A-Za-z_][A-Za-z0-9_]*|\*)"
                r"(?:\s+AS\s+[A-Za-z_][A-Za-z0-9_]*)?",
                expression,
                re.IGNORECASE,
            )
            if match:
                columns.append(match.group(1))
        return columns