import pytest

from backend.app.sql.sql_agent import SQLAgent


pytestmark = [pytest.mark.integration, pytest.mark.database]


def test_database_schema_and_campaign_query_are_read_only(
    database_connection, database_config
):
    with database_connection.cursor() as cursor:
        cursor.execute(
            "SELECT table_name FROM information_schema.tables "
            "WHERE table_schema = 'public' AND table_name = "
            "'marketing_campaigns'"
        )
        assert cursor.fetchone() == ("marketing_campaigns",)

        cursor.execute(
            "SELECT campaign_id, revenue_generated "
            "FROM marketing_campaigns WHERE campaign_id = %s",
            ("CMP-021",),
        )
        row = cursor.fetchone()

    assert row is not None
    assert row[0] == "CMP-021"


def test_sql_agent_pipeline_uses_real_database(
    database_connection, database_config
):
    agent = SQLAgent(**database_config, max_rows=100)
    response = agent.answer(
        "What was the revenue generated by campaign CMP-021?"
    )

    assert response["validation"]["valid"] is True
    assert response["result"]["row_count"] == 1
    assert response["result"]["rows"][0][0] == "CMP-021"
