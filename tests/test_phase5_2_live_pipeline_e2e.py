"""End-to-end live API validation suite for Phase 5.2.
Tests POST /api/reports directly against the live server at http://127.0.0.1:8000
for all six report types in both PDF and XLSX formats.
Audits binary PDF text with PyMuPDF and Excel sheets with openpyxl.
"""

import io
import json
import pytest
import pymupdf
import openpyxl
import requests

BASE_URL = "http://127.0.0.1:8000"

REPORT_TYPES = [
    ("executive_performance", "Executive Performance Report"),
    ("sales_performance", "Sales Performance & Merchandise Turnover"),
    ("campaign_performance", "Omnichannel Marketing & Campaign Performance"),
    ("customer_intelligence", "Customer Intelligence & Loyalty Stratification"),
    ("operations_fulfillment", "Logistics, Carrier SLA & Fulfillment Health"),
    ("custom_report", "Multi-Departmental Commercial Intelligence Synthesis"),
]


@pytest.fixture(scope="session")
def check_server():
    """Ensure backend server is running on port 8000."""
    try:
        resp = requests.get(f"{BASE_URL}/docs", timeout=5)
        assert resp.status_code == 200
    except Exception as e:
        pytest.fail(f"Backend server is not running on {BASE_URL}: {e}")


@pytest.mark.parametrize("report_type,title", REPORT_TYPES)
def test_live_pdf_export_structure_and_epistemic_rigor(check_server, report_type, title):
    """Test PDF generation via POST /api/reports and audit extracted text."""
    payload = {
        "report_type": report_type,
        "format": "pdf",
        "period": "all_time",
        "title": title,
        "sections": {
            "include_executive_summary": True,
            "include_kpi_cards": True,
            "include_charts": True,
            "include_detailed_tables": True,
            "include_observations": True,
            "include_recommendations": True,
            "include_audit_trail": True,
        },
    }

    resp = requests.post(f"{BASE_URL}/api/reports", json=payload, timeout=30)
    assert resp.status_code == 200, f"HTTP Error {resp.status_code}: {resp.text}"
    assert resp.headers.get("content-type") == "application/pdf"
    content = resp.content

    # 1. Binary validation
    assert content.startswith(b"%PDF-"), "Deliverable lacks %PDF- header."
    assert len(content) > 30000, f"PDF file size {len(content)} is under 30KB."

    # 2. PyMuPDF inspection
    pdf_doc = pymupdf.open(stream=content, filetype="pdf")
    num_pages = len(pdf_doc)
    assert num_pages >= 3, f"PDF pages ({num_pages}) is fewer than 3 pages."

    full_text = " ".join(page.get_text() for page in pdf_doc)
    text_lower = full_text.lower()

    # Universal epistemic bans across ALL reports
    assert "3-5% aov" not in text_lower, "PDF contains ungrounded projection: 3-5% AOV uplift"
    assert "3–5% aov" not in text_lower, "PDF contains ungrounded projection: 3–5% AOV uplift"
    assert "3-5% uplift" not in text_lower, "PDF contains ungrounded projection: 3-5% uplift"
    assert "over 65% of gross revenue is generated by electronics" not in text_lower, "Contains outdated 65% claim"
    assert "electronics and appliances" not in text_lower, "Mentions nonexistent appliances category"

    # Category-specific validation
    if report_type == "executive_performance":
        assert "orders containing" in text_lower and "category" in text_lower, "Missing Orders Containing Category reach header"
        assert "Gross List Value" in full_text
        assert "Top Marketing Campaigns by Capital Efficiency" in full_text
        assert "CMP-012" in full_text
        pos_012 = full_text.find("CMP-012")
        pos_037 = full_text.find("CMP-037")
        pos_007 = full_text.find("CMP-007")
        if pos_012 != -1 and pos_037 != -1:
            assert pos_012 < pos_037, "CMP-012 should appear before CMP-037 in ROAS ranking"
        if pos_037 != -1 and pos_007 != -1:
            assert pos_037 < pos_007, "CMP-037 should appear before CMP-007 in ROAS ranking"

    elif report_type == "campaign_performance":
        assert "Top Marketing Campaigns by Capital Efficiency" in full_text
        assert "Top Marketing Campaigns by Commercial Scale" in full_text
        assert "CMP-012" in full_text
        assert "CMP-007" in full_text
        assert "10-15%" not in text_lower, "Contains unsupported 10-15% reallocation projection"
        assert "attribution" in text_lower, "Must qualify marketing attribution methodology"

    elif report_type == "customer_intelligence":
        assert "Customer Loyalty Tier Stratification" in full_text
        assert "Gold" in full_text
        assert "Bronze" in full_text
        assert "90-day" not in text_lower, "Contains unverified 90-day dormancy claim"
        assert "repeat-order uplift" not in text_lower, "Contains ungrounded repeat-order uplift claim"

    elif report_type == "operations_fulfillment":
        assert "Carrier Dispatch & Delivery Transit SLA" in full_text or "Carrier" in full_text
        assert "BlueDart" in full_text or "DTDC" in full_text
        assert "0.0% delivery" not in text_lower, "Contains invalid 0.0% delivery claim"
        assert "56.3%" in full_text or "71.9%" in full_text, "Must report true delivery metrics"

    elif report_type == "sales_performance":
        assert "Revenue Contribution by Merchandise Category" in full_text
        assert "Top Performing SKUs" in full_text
        assert "Gross List Value" in full_text

    elif report_type == "custom_report":
        assert "infrastructure resilience" not in text_lower, "Contains unverified infrastructure claim"
        assert "inventory latency" not in text_lower, "Contains unverified inventory latency claim"


@pytest.mark.parametrize("report_type,title", REPORT_TYPES)
def test_live_xlsx_export_structure(check_server, report_type, title):
    """Test XLSX generation via POST /api/reports and audit openpyxl worksheets."""
    payload = {
        "report_type": report_type,
        "format": "xlsx",
        "period": "all_time",
        "title": title,
        "sections": {
            "include_executive_summary": True,
            "include_kpi_cards": True,
            "include_charts": True,
            "include_detailed_tables": True,
            "include_observations": True,
            "include_recommendations": True,
            "include_audit_trail": True,
        },
    }

    resp = requests.post(f"{BASE_URL}/api/reports", json=payload, timeout=30)
    assert resp.status_code == 200, f"HTTP Error {resp.status_code}: {resp.text}"
    assert "spreadsheet" in resp.headers.get("content-type", "") or "openxmlformats" in resp.headers.get("content-type", "")
    content = resp.content

    assert content.startswith(b"PK"), "XLSX deliverable lacks PK magic bytes."
    assert len(content) > 10000, f"XLSX file size {len(content)} is under 10KB."

    wb = openpyxl.load_workbook(io.BytesIO(content))
    sheets = wb.sheetnames
    assert len(sheets) >= 3, f"XLSX workbook has fewer than 3 sheets: {sheets}"
    assert "Executive Summary" in sheets
    assert "KPI Scorecard" in sheets
