def test_controlled_self_repair_resolves_contradiction(data_layer, repair_engine):
    """Verify ReportRepairEngine diagnoses and safely repairs category contradiction."""
    data = data_layer.retrieve_and_validate(ReportCategory.EXECUTIVE_PERFORMANCE, ReportPeriod.ALL_TIME)

    request = ReportRequestModel(
        category=ReportCategory.EXECUTIVE_PERFORMANCE,
        format=ReportFormat.PDF,
        period=ReportPeriod.ALL_TIME,
    )
    doc = ReportDocument(
        request=request,
        category=request.category,
        period=request.period,
        title="Test Report",
        period_label=data.period_label,
        period_start=data.start_date.isoformat(),
        period_end=data.end_date.isoformat(),
        generated_at=data.start_date,
        executive_summary="Summary text",
        kpi_cards=[],
        tables=[],
        key_drivers=[],
        risk_observations=["Category Concentration Risk: Over 65% of gross revenue is generated by Electronics and Home Appliances."],
        recommendations=[],
        methodology="",
        sources=[],
        raw_metrics={},
    )

    issues = ["Contradiction in category concentration: text claims ~65% for Electronics and Home Appliances."]
    repaired_doc, all_resolved, logs = repair_engine.diagnose_and_repair(doc, issues, data)

    assert len(logs) > 0
    assert logs[0].status == "RESOLVED"
    assert "Over 65%" not in repaired_doc.risk_observations[0]


