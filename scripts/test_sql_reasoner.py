from backend.app.sql.schema_inspector import DatabaseSchemaLoader
from backend.app.sql.sql_reasoner import SQLReasoner
from database_config import load_database_config

def print_plan(plan: dict):
    print("\nStructured Query Plan:")
    print("-" * 70)

    for key, value in plan.items():
        print(f"{key}: {value}")


def main():
    print("=" * 70)
    print("TESTING SQL REASONER")
    print("=" * 70)

    schema_loader = DatabaseSchemaLoader(**load_database_config())

    reasoner = SQLReasoner(schema_loader)

    # ---------------------------------------------------------------
    # Test 1: Revenue
    # ---------------------------------------------------------------

    question = "What was the revenue generated by campaign CMP-021?"

    print("\nTest 1: Revenue")
    print("-" * 70)
    print(f"Question: {question}")

    plan = reasoner.reason(question)

    print_plan(plan)

    assert plan["intent"] == "REVENUE"
    assert plan["entity_type"] == "campaign"
    assert plan["entity_id"] == "CMP-021"
    assert plan["table"] == "marketing_campaigns"
    assert plan["operation"] == "SELECT"
    assert "revenue_generated" in plan["columns"]

    print("\nPASS")


    # ---------------------------------------------------------------
    # Test 2: Spend
    # ---------------------------------------------------------------

    question = "What was the spend of campaign CMP-021?"

    print("\nTest 2: Spend")
    print("-" * 70)
    print(f"Question: {question}")

    plan = reasoner.reason(question)

    print_plan(plan)

    assert plan["intent"] == "SPEND"
    assert plan["entity_id"] == "CMP-021"
    assert "actual_spend" in plan["columns"]

    print("\nPASS")


    # ---------------------------------------------------------------
    # Test 3: Conversions
    # ---------------------------------------------------------------

    question = "How many conversions did campaign CMP-021 generate?"

    print("\nTest 3: Conversions")
    print("-" * 70)
    print(f"Question: {question}")

    plan = reasoner.reason(question)

    print_plan(plan)

    assert plan["intent"] == "CONVERSIONS"
    assert plan["entity_id"] == "CMP-021"
    assert "conversions" in plan["columns"]

    print("\nPASS")


    # ---------------------------------------------------------------
    # Test 4: Campaign performance
    # ---------------------------------------------------------------

    question = "What was the performance of campaign CMP-021?"

    print("\nTest 4: Campaign Performance")
    print("-" * 70)
    print(f"Question: {question}")

    plan = reasoner.reason(question)

    print_plan(plan)

    assert plan["intent"] == "CAMPAIGN_PERFORMANCE"
    assert plan["entity_id"] == "CMP-021"

    assert "actual_spend" in plan["columns"]
    assert "revenue_generated" in plan["columns"]
    assert "conversions" in plan["columns"]
    assert "clicks" in plan["columns"]

    print("\nPASS")


    # ---------------------------------------------------------------
    # Test 5: Missing campaign ID
    # ---------------------------------------------------------------

    print("\nTest 5: Missing Campaign ID")
    print("-" * 70)

    question = "What was the revenue generated by the campaign?"

    try:
        reasoner.reason(question)
        raise AssertionError(
            "Missing campaign ID should have raised ValueError."
        )

    except ValueError as error:
        print(f"Expected error: {error}")

    print("PASS")


    # ---------------------------------------------------------------
    # Test 6: Unsupported question
    # ---------------------------------------------------------------

    print("\nTest 6: Unsupported Question")
    print("-" * 70)

    question = "What is the average order value of customers?"

    try:
        reasoner.reason(question)
        raise AssertionError(
            "Unsupported question should have raised ValueError."
        )

    except ValueError as error:
        print(f"Expected error: {error}")

    print("PASS")


    print("\n" + "=" * 70)
    print("SQL REASONER TEST COMPLETED SUCCESSFULLY")
    print("=" * 70)


if __name__ == "__main__":
    main()