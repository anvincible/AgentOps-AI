@pytest.mark.parametrize(
    "cat_str",
    [
        "executive_performance",
        "sales_performance",
        "campaign_performance",
        "customer_intelligence",
        "operations_fulfillment",
        "custom_report",
    ],
)
def test_all_report_categories_generate_valid_pdf_and_xlsx(report_agent, cat_str):
    """Verify all report categories generate valid PDF and XLSX deliverables."""
    # PDF
    pdf_bytes, pdf_fn, pdf_mime = report_agent.generate(
        report_type=cat_str,
        file_format="pdf",
        use_enterprise=True,
    )
    assert pdf_bytes.startswith(b"%PDF-")
    assert len(pdf_bytes) > 25000
    assert pdf_fn.endswith(".pdf")
    assert pdf_mime == "application/pdf"

    # XLSX
    xlsx_bytes, xlsx_fn, xlsx_mime = report_agent.generate(
        report_type=cat_str,
        file_format="xlsx",
        use_enterprise=True,
    )
    assert xlsx_bytes.startswith(b"PK")
    assert len(xlsx_bytes) > 10000
    assert xlsx_fn.endswith(".xlsx")

    # Workbook sheet count & structure
    wb = openpyxl.load_workbook(io.BytesIO(xlsx_bytes))
    assert len(wb.sheetnames) >= 3
    assert "Executive Summary" in wb.sheetnames
    assert "KPI Scorecard" in wb.sheetnames
