from backend.app.sql.schema_inspector import DatabaseSchemaLoader
from backend.app.sql.sql_reasoner import SQLReasoner
from backend.app.sql.sql_generator import SQLGenerator
from backend.app.database_config import load_database_config


def main():
    print("=" * 70)
    print("TESTING SQL REASONER + SQL GENERATOR")
    print("=" * 70)

    db_config = load_database_config(require_explicit=True)
    schema_loader = DatabaseSchemaLoader(
        **db_config,
    )

    reasoner = SQLReasoner(schema_loader)
    generator = SQLGenerator(schema_loader)

    questions = [
        "What was the revenue generated by campaign CMP-021?",
        "What was the spend of campaign CMP-021?",
        "How many conversions did campaign CMP-021 generate?",
        "What was the performance of campaign CMP-021?",
    ]

    for index, question in enumerate(questions, start=1):

        print("\n" + "=" * 70)
        print(f"TEST {index}")
        print("=" * 70)

        print(f"\nQuestion:\n{question}")

        # Step 1: Reason about the question
        plan = reasoner.reason(question)

        print("\nReasoning Plan:")
        print("-" * 70)

        for key, value in plan.items():
            print(f"{key}: {value}")

        # Step 2: Generate SQL from the reasoning plan
        sql = generator.generate_sql(plan)

        print("\nGenerated SQL:")
        print("-" * 70)
        print(sql)

        assert "marketing_campaigns" in sql
        assert "CMP-021" in sql

        print("\nPASS")

    print("\n" + "=" * 70)
    print("REASONER + GENERATOR TEST COMPLETED SUCCESSFULLY")
    print("=" * 70)


if __name__ == "__main__":
    main()