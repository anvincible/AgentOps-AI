@pytest.mark.unit
def test_return_rate_query_passes_validation(schema, schema_loader):
    plan = SQLReasoner(schema_loader).reason("What is the return rate?")
    sql = SQLGenerator(schema_loader).generate_sql(plan)

    result = SQLValidator(schema).validate(sql)

    assert result["valid"] is True, result["errors"]
    assert set(result["tables"]) == {"returns", "orders"}


@pytest.mark.unit
@pytest.mark.parametrize(
    "question",
    [
        "How many returns were made?",
        "What are the return reasons?",
        "What was the performance of campaign CMP-021?",
        "What is the ROI of campaign CMP-021?",
        "Compare campaigns CMP-021 and CMP-022.",
        "Give me an overall campaign summary.",
    ],
)
def test_existing_generated_queries_still_validate(
    question, schema, schema_loader
):
    sql = SQLGenerator(schema_loader).generate_sql(
        SQLReasoner(schema_loader).reason(question)
    )

    result = SQLValidator(schema).validate(sql)

    assert result["valid"] is True, result["errors"]


@pytest.mark.unit
@pytest.mark.parametrize(
    "sql",
    [
        "SELECT COUNT(*) AS return_count FROM returns;",
        "SELECT r.return_count FROM (SELECT COUNT(*) AS return_count "
        "FROM returns) AS r;",
        "SELECT return_id AS rid FROM returns;",
    ],
)
def test_validator_accepts_valid_derived_columns(sql, schema):
    assert SQLValidator(schema).validate(sql)["valid"] is True


@pytest.mark.unit
def test_validator_rejects_invalid_table_in_subquery(schema):
    result = SQLValidator(schema).validate(
        "SELECT r.n FROM (SELECT COUNT(*) AS n FROM secret_table) AS r;"
    )

    assert result["valid"] is False
    assert any("secret_table" in error for error in result["errors"])


@pytest.mark.unit
@pytest.mark.parametrize(
    "sql",
    [
        "SELECT bogus_col FROM returns;",
        "SELECT bogus_col AS bogus_col FROM returns;",
        "SELECT x.n FROM (SELECT bogus_col FROM returns) AS x;",
        "SELECT r.n FROM (SELECT bogus_col AS n FROM returns) AS r;",
    ],
)
def test_validator_rejects_invalid_underlying_columns(sql, schema):
    result = SQLValidator(schema).validate(sql)

    assert result["valid"] is False
    assert any("bogus_col" in error for error in result["errors"])


