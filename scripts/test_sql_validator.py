from backend.app.sql.schema_inspector import DatabaseSchemaLoader
from backend.app.sql.sql_generator import SQLGenerator
from backend.app.sql.sql_validator import SQLValidator
from database_config import load_database_config

def main():
    print("=" * 70)
    print("TESTING SQL VALIDATOR")
    print("=" * 70)

    # ---------------------------------------------------------
    # Load database schema
    # ---------------------------------------------------------

    schema_loader = DatabaseSchemaLoader(**load_database_config())

    schema = schema_loader.load_schema()

    # ---------------------------------------------------------
    # Create validator
    # ---------------------------------------------------------

    validator = SQLValidator(schema)

    # ---------------------------------------------------------
    # Test 1: Valid SQL generated by SQL Generator
    # ---------------------------------------------------------

    generator = SQLGenerator(schema_loader)

    question = "What was the revenue generated by campaign CMP-021?"

    print("\nTest 1: Valid SELECT query")
    print("-" * 70)

    generated_sql = generator.generate_sql(question)

    print("Generated SQL:")
    print(generated_sql)

    result = validator.validate(generated_sql)

    print("\nValidation result:")
    print(result)

    assert result["valid"] is True

    print("PASS")

    # ---------------------------------------------------------
    # Test 2: DROP
    # ---------------------------------------------------------

    print("\nTest 2: DROP statement")
    print("-" * 70)

    sql = "DROP TABLE customers;"

    result = validator.validate(sql)

    print(result)

    assert result["valid"] is False

    print("PASS")

    # ---------------------------------------------------------
    # Test 3: DELETE
    # ---------------------------------------------------------

    print("\nTest 3: DELETE statement")
    print("-" * 70)

    sql = "DELETE FROM customers;"

    result = validator.validate(sql)

    print(result)

    assert result["valid"] is False

    print("PASS")

    # ---------------------------------------------------------
    # Test 4: UPDATE
    # ---------------------------------------------------------

    print("\nTest 4: UPDATE statement")
    print("-" * 70)

    sql = """
    UPDATE customers
    SET customer_name = 'Test';
    """

    result = validator.validate(sql)

    print(result)

    assert result["valid"] is False

    print("PASS")

    # ---------------------------------------------------------
    # Test 5: Non-existent table
    # ---------------------------------------------------------

    print("\nTest 5: Non-existent table")
    print("-" * 70)

    sql = """
    SELECT *
    FROM fake_table;
    """

    result = validator.validate(sql)

    print(result)

    assert result["valid"] is False

    print("PASS")

    # ---------------------------------------------------------
    # Test 6: Empty SQL
    # ---------------------------------------------------------

    print("\nTest 6: Empty SQL")
    print("-" * 70)

    result = validator.validate("")

    print(result)

    assert result["valid"] is False

    print("PASS")

    print("\n" + "=" * 70)
    print("SQL VALIDATOR TEST COMPLETED SUCCESSFULLY")
    print("=" * 70)


if __name__ == "__main__":
    main()